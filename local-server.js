function toPg(sql) {
  let i = 0;
  return sql.replace(/\?/g, () => `$${++i}`);
}

async function initDb() {
  if (USE_POSTGRES) {
    await pool.query(POSTGRES_SCHEMA);
  } else {
    sqlite.exec(SQLITE_SCHEMA);
  }
}

async function all(sql, params = []) {
  if (USE_POSTGRES) return (await pool.query(toPg(sql), params)).rows;
  return sqlite.prepare(sql).all(...params);
}

async function one(sql, params = []) {
  if (USE_POSTGRES) return (await pool.query(toPg(sql), params)).rows[0] || null;
  return sqlite.prepare(sql).get(...params) || null;
}

async function exec(sql, params = []) {
  if (USE_POSTGRES) return await pool.query(toPg(sql), params);
  return sqlite.prepare(sql).run(...params);
}

async function insertId(sql, params = []) {
  if (USE_POSTGRES) {
    const clean = sql.trim().replace(/;$/, '') + ' RETURNING id';
    const row = (await pool.query(toPg(clean), params)).rows[0];
    return Number(row.id);
  }
  const result = sqlite.prepare(sql).run(...params);
  return Number(result.lastInsertRowid);
}

function addDays(date, offset) {
  const d = new Date(date);
  d.setUTCDate(d.getUTCDate() + offset);
  return d.toISOString().slice(0, 10);
}

function today() {
  return new Date().toISOString().slice(0, 10);
}

function hashToken(token) {
  return crypto.createHash('sha256').update(token).digest('hex');
}

function makePassword(password) {
  const salt = crypto.randomBytes(16).toString('hex');
  const hash = crypto.scryptSync(password, salt, 64).toString('hex');
  return { salt, hash };
}

function verifyPassword(password, user) {
  try {
    const candidate = crypto.scryptSync(password, user.password_salt, 64);
    return crypto.timingSafeEqual(candidate, Buffer.from(user.password_hash, 'hex'));
  } catch {
    return false;
  }
}

