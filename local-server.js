function parseCookies(req) {
  const raw = req.headers.cookie || '';
  const out = {};
  for (const part of raw.split(';')) {
    const [k, ...rest] = part.trim().split('=');
    if (k) out[k] = decodeURIComponent(rest.join('='));
  }
  return out;
}

async function sessionUser(req) {
  const token = parseCookies(req).trendova_session;
  if (!token) return null;
  const s = await one('SELECT s.user_id, s.expires_at, u.id, u.name, u.email FROM sessions s JOIN users u ON u.id=s.user_id WHERE s.token_hash=?', [hashToken(token)]);
  if (!s) return null;
  if (Date.now() > Number(s.expires_at)) {
    await exec('DELETE FROM sessions WHERE token_hash=?', [hashToken(token)]);
    return null;
  }
  return { id: Number(s.id), name: s.name, email: s.email };
}

async function requireUser(req, res) {
  const user = await sessionUser(req);
  if (!user) {
    sendJson(res, 401, { error: 'Unauthenticated' });
    return null;
  }
  return user;
}

