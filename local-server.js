function sendJson(res, status, data, extraHeaders = {}) {
  const body = JSON.stringify(data);
  res.writeHead(status, {
    'Content-Type': 'application/json; charset=utf-8',
    'Cache-Control': 'no-store',
    ...extraHeaders
  });
  res.end(body);
}

function sendText(res, status, text, contentType = 'text/plain; charset=utf-8') {
  res.writeHead(status, { 'Content-Type': contentType });
  res.end(text);
}

function bodyJson(req) {
  return new Promise((resolve, reject) => {
    let raw = '';
    req.on('data', chunk => {
      raw += chunk;
      if (raw.length > 1_000_000) {
        req.destroy();
        reject(new Error('Payload too large'));
      }
    });
    req.on('end', () => {
      try { resolve(raw ? JSON.parse(raw) : {}); }
      catch (err) { reject(err); }
    });
    req.on('error', reject);
  });
}

async function salesMomentum(businessId, keyword) {
  const products = await all('SELECT id,name FROM products WHERE business_id=? AND lower(name) LIKE ?', [businessId, `%${keyword.toLowerCase()}%`]);
  if (!products.length) return 0;
  const ids = products.map(p => Number(p.id));
  const recentFrom = addDays(new Date(), -10);
  const previousFrom = addDays(new Date(), -30);
  let recent = 0, previous = 0;
  for (const id of ids) {
    recent += Number((await one('SELECT COALESCE(SUM(units),0) units FROM sales WHERE business_id=? AND product_id=? AND sold_on>=?', [businessId,id,recentFrom]))?.units || 0);
    previous += Number((await one('SELECT COALESCE(SUM(units),0) units FROM sales WHERE business_id=? AND product_id=? AND sold_on<? AND sold_on>=?', [businessId,id,recentFrom,previousFrom]))?.units || 0);
  }
  if (!previous) return recent ? 10 : 0;
  const growth = (recent - previous) / previous;
  return Math.max(-5, Math.min(10, growth * 10));
}

async function recomputeTrends(businessId) {
  const signals = await all(`SELECT keyword,
    AVG(growth) growth, AVG(sentiment) sentiment, AVG(persistence) persistence,
    SUM(mentions) mentions, SUM(searches) searches,
    COUNT(DISTINCT source) sources
    FROM trend_signals WHERE business_id=? GROUP BY keyword`, [businessId]);
  for (const s of signals) {
    const salesBoost = await salesMomentum(businessId, s.keyword);
    const cross = Math.min(20, (Number(s.sources) / 3) * 20);
    const growth = Math.min(35, Math.max(0, Number(s.growth) / 100 * 35));
    const sent = Math.min(10, Math.max(0, ((Number(s.sentiment) + 1) / 2) * 10));
    const persistence = Math.min(15, Math.max(0, Number(s.persistence) / 100 * 15));
    const score = Math.round((growth + cross + sent + persistence + salesBoost) * 10) / 10;
    const status = score >= 65 ? 'Emerging Opportunity' : score >= 50 ? 'Watch' : 'Noise Risk';
    const evidence = `${Number(s.sources)} sumber, pertumbuhan ${Math.round(Number(s.growth))}%, persistence ${Math.round(Number(s.persistence))}%, sentiment ${Math.round(Number(s.sentiment)*100)}%${salesBoost ? `, sales momentum +${Math.round(salesBoost)} poin` : ''}`;
    const category = s.keyword === 'kimpul' ? 'Local Ingredient' : s.keyword === 'matcha' ? 'Beverage' : 'Emerging Signal';
    const action = status === 'Emerging Opportunity'
      ? `Jalankan eksperimen terbatas untuk ${s.keyword}`
      : status === 'Watch'
        ? `Pantau ${s.keyword} 7 hari dan validasi sumber tambahan`
        : `Jangan jadikan ${s.keyword} sebagai dasar produksi massal`;
    const existing = await one('SELECT id FROM trends WHERE business_id=? AND keyword=?', [businessId,s.keyword]);
    if (existing) {
      await exec('UPDATE trends SET category=?,score=?,status=?,evidence=?,recommended_action=?,updated_at=? WHERE id=?', [category,score,status,evidence,action,new Date().toISOString(),existing.id]);
    } else {
      await exec('INSERT INTO trends (business_id,keyword,category,score,status,evidence,recommended_action) VALUES (?,?,?,?,?,?,?)', [businessId,s.keyword,category,score,status,evidence,action]);
    }
  }
}

async function seedRecommendations(businessId) {
  const trends = await all('SELECT * FROM trends WHERE business_id=? ORDER BY score DESC LIMIT 5', [businessId]);
  for (const t of trends) {
    const exists = await one('SELECT id FROM recommendations WHERE business_id=? AND trend_id=?', [businessId,t.id]);
    if (exists) continue;
    await exec('INSERT INTO recommendations (business_id,trend_id,title,rationale,priority,action) VALUES (?,?,?,?,?,?)', [
      businessId, t.id, `Eksperimen ${t.keyword}`, `${t.evidence}. Uji secara terbatas sebelum keputusan produksi yang lebih besar.`, Number(t.score)>=65?'high':'medium', t.recommended_action
    ]);
  }
}

async function latestDashboard(b) {
  await recomputeTrends(b.id);
  const trends = await all('SELECT * FROM trends WHERE business_id=? ORDER BY score DESC', [b.id]);
  const top = trends[0] || null;
  const from30 = addDays(new Date(), -30);
  const totalRevenue = Number((await one('SELECT COALESCE(SUM(revenue),0) revenue FROM sales WHERE business_id=? AND sold_on>=?', [b.id,from30]))?.revenue || 0);
  const totalUnits = Number((await one('SELECT COALESCE(SUM(units),0) units FROM sales WHERE business_id=? AND sold_on>=?', [b.id,from30]))?.units || 0);
  const activeOpps = trends.filter(t => t.status === 'Emerging Opportunity').length;
  const openRec = Number((await one("SELECT COUNT(*) c FROM recommendations WHERE business_id=? AND status='open'", [b.id]))?.c || 0);
  return { business:b, metrics:{activeOpps,openRec,totalRevenue,totalUnits}, topTrend:top, trends:trends.slice(0,5) };
}

const mime = { '.html':'text/html; charset=utf-8', '.js':'text/javascript; charset=utf-8', '.css':'text/css; charset=utf-8', '.svg':'image/svg+xml', '.json':'application/json' };

function serveStatic(req,res) {
  let pathname = new URL(req.url, `http://${req.headers.host || 'localhost'}`).pathname;
  if (pathname === '/') pathname = '/index.html';
  const safe = path.normalize(pathname).replace(/^([.][.][\\/])+/, '');
  const file = path.join(PUBLIC, safe);
  if (!file.startsWith(PUBLIC)) return sendText(res,403,'Forbidden');
  fs.readFile(file, (err, data) => {
    if (err) return sendText(res,404,'Not found');
    res.writeHead(200, {
      'Content-Type': mime[path.extname(file)] || 'application/octet-stream',
      'Cache-Control': 'no-cache',
      'X-Content-Type-Options': 'nosniff',
      'X-Frame-Options': 'SAMEORIGIN',
      'Referrer-Policy': 'strict-origin-when-cross-origin'
    });
    res.end(data);
  });
}

